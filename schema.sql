-- WARNING: This schema is for context only and is not meant to be run directly by the system.
-- The user will manually apply this in Supabase.

-- 1. Create Enums for strict typing safely
DO $$ BEGIN
    CREATE TYPE user_role AS ENUM ('employee', 'admin', 'guest', 'ai_agent', 'supervisor');
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
    CREATE TYPE map_type AS ENUM ('office', 'meeting_room', 'break_room');
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

-- 2. Profiles (Combines human users and AI agents)
CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  email text,
  display_name text,
  role user_role NOT NULL DEFAULT 'employee',
  avatar_url text,
  status text DEFAULT 'offline', -- online, busy, offline
  camera_enabled boolean DEFAULT false,
  microphone_enabled boolean DEFAULT false,
  accessible_maps text[] DEFAULT '{}',
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  PRIMARY KEY (id)
);

-- 3. AI Agents Configuration (The Twist)
CREATE TABLE IF NOT EXISTS public.ai_agents (
  id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  agent_type text NOT NULL, -- e.g., 'receptionist', 'scribe'
  system_prompt text NOT NULL,
  assigned_map_id text, -- the map they spawn in
  PRIMARY KEY (id)
);

-- 4. Spatial Maps
CREATE TABLE IF NOT EXISTS public.maps (
  id text NOT NULL, -- e.g., 'main-office'
  name text NOT NULL,
  type map_type NOT NULL DEFAULT 'office',
  background_url text, -- URL to the floorplan image
  width numeric NOT NULL,
  height numeric NOT NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  PRIMARY KEY (id)
);

-- 5. Zones within Maps (Rooms, desks)
CREATE TABLE IF NOT EXISTS public.map_zones (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  room_id text NOT NULL REFERENCES public.maps(id) ON DELETE CASCADE,
  name text NOT NULL,
  zone_type text DEFAULT 'meeting', -- 'meeting', 'desk', 'private'
  x numeric NOT NULL,
  y numeric NOT NULL,
  width numeric NOT NULL,
  height numeric NOT NULL,
  max_capacity integer DEFAULT 10,
  PRIMARY KEY (id)
);

-- 6. Persistent Text Chat
CREATE TABLE IF NOT EXISTS public.messages (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  sender_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  map_id text REFERENCES public.maps(id) ON DELETE CASCADE,
  zone_id uuid REFERENCES public.map_zones(id) ON DELETE CASCADE, -- null if global map chat
  content text NOT NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  PRIMARY KEY (id)
);

-- 7. Voice Transcripts (Used for generating minutes)
CREATE TABLE IF NOT EXISTS public.transcripts (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  zone_id uuid NOT NULL REFERENCES public.map_zones(id) ON DELETE CASCADE,
  user_name text NOT NULL,
  content text NOT NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  PRIMARY KEY (id)
);

-- 8. AI Outputs (Generated by 'scribe' agents or humans)
CREATE TABLE IF NOT EXISTS public.meeting_minutes (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  zone_id uuid NOT NULL REFERENCES public.map_zones(id) ON DELETE CASCADE,
  generated_by uuid NOT NULL REFERENCES public.profiles(id),
  summary text NOT NULL,
  action_items text NOT NULL,
  created_at timestamp with time zone DEFAULT now(),
  PRIMARY KEY (id)
);

-- Enable RLS (Row Level Security) - Recommended
ALTER TABLE IF EXISTS public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE IF EXISTS public.maps ENABLE ROW LEVEL SECURITY;
ALTER TABLE IF EXISTS public.map_zones ENABLE ROW LEVEL SECURITY;
ALTER TABLE IF EXISTS public.messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE IF EXISTS public.transcripts ENABLE ROW LEVEL SECURITY;
ALTER TABLE IF EXISTS public.meeting_minutes ENABLE ROW LEVEL SECURITY;